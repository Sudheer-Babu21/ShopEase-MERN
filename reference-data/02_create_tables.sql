-- ====================================================================
-- Script: 02_create_tables.sql
-- Description: Creates relational schema tables, constraints, and indexes
-- Target: Oracle Database XE 10g (and compatible)
-- Execute as: shoppingcart user (or admin schema)
-- ====================================================================

PROMPT [2/5] Creating relational schema tables...

-- Safe drop sequence if previously created
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN 
        ('ORDER_ITEMS', 'ORDERS', 'CART_ITEMS', 'PRODUCTS', 'CATEGORIES', 'USERS')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/

-- 1. USERS TABLE
CREATE TABLE USERS (
    USER_ID         NUMBER,
    NAME            VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(100) NOT NULL,
    PASSWORD_HASH   VARCHAR2(255) NOT NULL,
    PHONE           VARCHAR2(20),
    ROLE            VARCHAR2(20) DEFAULT 'CUSTOMER' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_USERS_ROLE CHECK (ROLE IN ('ADMIN', 'CUSTOMER'))
);

-- 2. CATEGORIES TABLE
CREATE TABLE CATEGORIES (
    CATEGORY_ID     NUMBER,
    NAME            VARCHAR2(100) NOT NULL,
    DESCRIPTION     VARCHAR2(500),
    CONSTRAINT PK_CATEGORIES PRIMARY KEY (CATEGORY_ID),
    CONSTRAINT UQ_CATEGORIES_NAME UNIQUE (NAME)
);

-- 3. PRODUCTS TABLE
CREATE TABLE PRODUCTS (
    PRODUCT_ID      NUMBER,
    CATEGORY_ID     NUMBER NOT NULL,
    NAME            VARCHAR2(150) NOT NULL,
    DESCRIPTION     VARCHAR2(1000),
    PRICE           NUMBER(10, 2) NOT NULL,
    STOCK_QTY       NUMBER(8) NOT NULL,
    IMAGE_PATH      VARCHAR2(255),
    IS_ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PRODUCTS PRIMARY KEY (PRODUCT_ID),
    CONSTRAINT FK_PRODUCTS_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID),
    CONSTRAINT CHK_PRODUCTS_PRICE CHECK (PRICE >= 0),
    CONSTRAINT CHK_PRODUCTS_STOCK CHECK (STOCK_QTY >= 0),
    CONSTRAINT CHK_PRODUCTS_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

-- 4. CART_ITEMS TABLE
CREATE TABLE CART_ITEMS (
    CART_ITEM_ID    NUMBER,
    USER_ID         NUMBER NOT NULL,
    PRODUCT_ID      NUMBER NOT NULL,
    QUANTITY        NUMBER(5) NOT NULL,
    CONSTRAINT PK_CART_ITEMS PRIMARY KEY (CART_ITEM_ID),
    CONSTRAINT FK_CART_ITEMS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CART_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_CART_USER_PROD UNIQUE (USER_ID, PRODUCT_ID),
    CONSTRAINT CHK_CART_QUANTITY CHECK (QUANTITY > 0)
);

-- 5. ORDERS TABLE
CREATE TABLE ORDERS (
    ORDER_ID            NUMBER,
    USER_ID             NUMBER NOT NULL,
    ORDER_DATE          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    TOTAL_AMOUNT        NUMBER(10, 2) NOT NULL,
    STATUS              VARCHAR2(20) DEFAULT 'PLACED' NOT NULL,
    SHIPPING_ADDRESS    VARCHAR2(500) NOT NULL,
    PAYMENT_METHOD      VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_ORDERS PRIMARY KEY (ORDER_ID),
    CONSTRAINT FK_ORDERS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_ORDERS_TOTAL CHECK (TOTAL_AMOUNT >= 0),
    CONSTRAINT CHK_ORDERS_STATUS CHECK (STATUS IN ('PLACED', 'PACKED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT CHK_ORDERS_PAYMENT CHECK (PAYMENT_METHOD IN ('COD', 'MOCK'))
);

-- 6. ORDER_ITEMS TABLE
CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID   NUMBER,
    ORDER_ID        NUMBER NOT NULL,
    PRODUCT_ID      NUMBER NOT NULL,
    QUANTITY        NUMBER(5) NOT NULL,
    UNIT_PRICE      NUMBER(10, 2) NOT NULL,
    CONSTRAINT PK_ORDER_ITEMS PRIMARY KEY (ORDER_ITEM_ID),
    CONSTRAINT FK_ORDER_ITEMS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID),
    CONSTRAINT FK_ORDER_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT CHK_ORDER_ITEMS_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CHK_ORDER_ITEMS_PRICE CHECK (UNIT_PRICE >= 0)
);

-- Performance Indexes on Foreign Keys and Query Columns
CREATE INDEX IDX_PRODUCTS_CAT ON PRODUCTS(CATEGORY_ID);
CREATE INDEX IDX_PRODUCTS_ACTIVE ON PRODUCTS(IS_ACTIVE);
CREATE INDEX IDX_CART_USER ON CART_ITEMS(USER_ID);
CREATE INDEX IDX_ORDERS_USER ON ORDERS(USER_ID);
CREATE INDEX IDX_ORDER_ITEMS_ORDER ON ORDER_ITEMS(ORDER_ID);
CREATE INDEX IDX_ORDER_ITEMS_PROD ON ORDER_ITEMS(PRODUCT_ID);

PROMPT Tables, constraints, and indexes created successfully.
